class Command(BaseCommand):
    help = "Seed ~100 realistic retail products with positive stock into a tenant"

    def add_arguments(self, parser):
        parser.add_argument(
            "--tenant-id",
            type=int,
            default=4,
            help="Tenant ID to seed products into (default: 4)",
        )

    def handle(self, *args, **options):
        tenant_id = options["tenant_id"]
        try:
            tenant = Tenant.objects.get(id=tenant_id)
        except Tenant.DoesNotExist:
            self.stderr.write(self.style.ERROR(f"Tenant with ID {tenant_id} not found."))
            return

        owner = User.objects.filter(tenant=tenant, role="owner").first()
        if not owner:
            owner = User.objects.filter(tenant=tenant).first()

        self.stdout.write(
            self.style.NOTICE(
                f"--- Seeding for Tenant: '{tenant.name}' (ID: {tenant.id}) ---"
            )
        )

        # 1. Ensure Categories exist
        categories = {}
        for cat_data in CATEGORIES_DATA:
            category, created = Category.objects.get_or_create(
                tenant=tenant,
                kod=cat_data["kod"],
                defaults={
                    "name": cat_data["name"],
                    "currency": cat_data["currency"],
                },
            )
            if not created and category.name != cat_data["name"]:
                category.name = cat_data["name"]
                category.save(update_fields=["name"])
            categories[cat_data["kod"]] = category

        self.stdout.write(self.style.SUCCESS(f"Loaded {len(categories)} categories."))

        # 2. Seed Products
        created_count = 0
        skipped_count = 0
        intake_count = 0
        total_units = Decimal("0")
        total_cost = Decimal("0")

        for item in PRODUCTS_DATA:
            category = categories.get(item["category_kod"])
            if not category:
                self.stderr.write(self.style.WARNING(f"Category {item['category_kod']} not found for {item['name']}"))
                continue

            # Check if product already exists
            product = Product.objects.filter(tenant=tenant, name=item["name"]).first()
            if not product:
                with transaction.atomic():
                    product = ProductService.create(
                        tenant=tenant,
                        name=item["name"],
                        category=category,
                        price_partner=item["price_partner"],
                        price_min=item["price_min"],
                        price_recommended=item["price_recommended"],
                        unit=item["unit"],
                        barcode=item.get("barcode"),
                    )
                    created_count += 1
            else:
                skipped_count += 1
                # If variant doesn't have barcode, update it
                variant = product.variants.first()
                if variant and not variant.barcode and item.get("barcode"):
                    variant.barcode = item["barcode"]
                    variant.save(update_fields=["barcode"])

            variant = product.variants.first()
            if not variant:
                continue

            stock = getattr(variant, "stock", None)
            if not stock or stock.quantity <= 0:
                StockService.intake(
                    tenant=tenant,
                    product_variant=variant,
                    quantity=item["quantity"],
                    cost_price=item["cost_price"],
                    created_by=owner,
                    note="Boshlang'ich qoldiq (Avtomatik to'ldirish)",
                )
                intake_count += 1
                total_units += item["quantity"]
                total_cost += (item["quantity"] * item["cost_price"])
            else:
                total_units += stock.quantity
                total_cost += (stock.quantity * (stock.last_cost_price or item["cost_price"]))

        self.stdout.write(
            self.style.SUCCESS(
                f"\nFinished seeding products:\n"
                f"- Yangi yaratilgan mahsulotlar: {created_count}\n"
                f"- Mavjud bo'lgan mahsulotlar: {skipped_count}\n"
                f"- Kirim qilingan partiyalar: {intake_count}\n"
                f"- Jami ombordagi qoldiq (dona/kg): {total_units}\n"
                f"- Jami tan narxi qiymati: {total_cost:,.2f} UZS\n"
                f"- Tenant ombori: '{tenant.name}'\n"
            )
        )
